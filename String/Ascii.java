package String;

public class Ascii {
    public static void main(String[] args) {
        char ch='a';
        System.out.println(ch+0);
        System.out.println((char)ch+0);
        System.out.println((char)ch+1);
        System.out.println((int)'a'-'0');
        int digit='2'-'0';
        System.out.println(digit); 
    }
}
